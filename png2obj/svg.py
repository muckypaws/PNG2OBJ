# Indices into a 4-entry illusion colour table:
# [Light Block, Dark Block, Light Pixel, Dark Pixel].
LIGHT_BLOCK_INDEX = 0
DARK_BLOCK_INDEX = 1
LIGHT_PIXEL_INDEX = 2
DARK_PIXEL_INDEX = 3


class SvgState:
    """Per-run SVG render state (buffer, canvas size, counts, illusion config).

    Attributes:
        data_list (list[str]): accumulated SVG fragments written to file.
        illusion_array (list[list[str]]): raster grid for illusion generation.
        canvas_width, canvas_height (float): running max canvas size in mm.
        png_pixel_count, grid_count, optical_illusion_count,
        light_count, dark_count (int): running tallies for the summary report.
        illusion_max_streak (int): max run length before toggling (ILLUSION_MAX_STREAK).
        illusion_colour_table (list[str]): active 4-colour illusion palette.
        illusion_type_circle (bool): circular vs diagonal illusion.
    """

    def __init__(self):
        self.data_list = []
        self.illusion_array = []
        self.canvas_width = 0.0
        self.canvas_height = 0.0
        self.png_pixel_count = 0
        self.grid_count = 0
        self.optical_illusion_count = 0
        self.light_count = 0
        self.dark_count = 0
        self.illusion_max_streak = 3
        self.illusion_colour_table = ["#3F53FF", "#020078", "#D93C41", "#781314"]
        self.illusion_type_circle = False
