"""SVG generation constants and accumulating render state.

Constants (header, preset colour sets, palette indices) are immutable and live
at module level. The per-run mutable state (output buffer, canvas size, running
counts, illusion settings) is gathered into SvgState, replacing the former loose
SVG_* / ILLUSION_* module globals. Defaults match the original global values.
"""

